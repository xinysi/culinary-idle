DEFAULT_HINT = ('一件完整的东西（按物品名判断它是什么，画出它本来的形）', '按材质取色，饱和明快')


def main():
    raw = open(SRC, 'rb').read()
    items = json.loads(raw.decode('utf-16') if raw[:2] in (b'\xff\xfe', b'\xfe\xff') else raw.decode('utf-8'))
    bycat = collections.defaultdict(list)
    for it in items:
        if it['type'] == 'seed' and it['name'].endswith('种子'):
            bycat['种子'].append(it)
        else:
            bycat[it['categoryLabel'] or it['category'] or '未分类'].append(it)

    os.makedirs(OUTDIR, exist_ok=True)
    idx = ['# 全库物品图提示词（按类别分文件）', '',
           '每件 = **正文 + 尾巴**；把这一条发给文生图即可。',
           '判据：缩到 **24px** 能读出剪影；**主体必须是实心的一块**（这批就是为「被去背挖空」重出的）。', '',
           '| 类别 | 件数 | 文件 |', '| --- | --- | --- |']
    for cat, lst in sorted(bycat.items(), key=lambda kv: -len(kv[1])):
        fn = os.path.join(OUTDIR, f'{cat}.md')
        lines = [f'# {cat}（{len(lst)} 件）', '', '> 每件 = **正文 + 尾巴**（下面这条）。', '',
                 '**尾巴（统一）**', '```', TAIL, '```', '']
        for it in sorted(lst, key=lambda x: (x['level'] or 0, x['name'])):
            hint = CAT_HINT.get(it['category']) or CAT_HINT.get(cat) or DEFAULT_HINT
            lv = f'Lv{it["level"]} 解锁 · ' if it.get('level') else ''
            body = (f'游戏物品图标：{cat}——{it["name"]}（{lv}{it["type"]}）。'
                    f'{hint[0]}。配色：{hint[1]}。{REQ}')
            lines += [f'## {it["name"]}', '```', body, TAIL, '```', '']
        open(fn, 'w', encoding='utf-8').write('\n'.join(lines))
        idx.append(f'| {cat} | {len(lst)} | `docs/全库提示词/{cat}.md` |')
    open(os.path.join(OUTDIR, '_索引.md'), 'w', encoding='utf-8').write('\n'.join(idx))
    print('共 %d 类 / %d 件 → %s' % (len(bycat), len(items), OUTDIR))


if __name__ == '__main__':
    main()

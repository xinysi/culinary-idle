/** 家族形态兜底（特征里没写的） */
function shapeOf(crop) {
  if (/谷|麦|稻|玉米|大麦|高粱|薏/.test(crop)) return '细长颖果粒'
  if (/瓜$|瓜种/.test(crop) || /西瓜|南瓜|冬瓜|黄瓜|哈密瓜|甜瓜/.test(crop)) return '扁卵瓜籽'
  if (/豆$|花生/.test(crop)) return '肾形豆粒'
  if (/莓|桑葚|覆盆子/.test(crop)) return '细小籽点粒'
  if (/参|术|芪|归|芎|冬|麻|斛|精|芷|苓|草$/.test(crop)) return '药草种粒'
  if (/菇|耳|茸|灵芝|松露/.test(crop)) return '菌种块带孢子粉'
  return '饱满种粒'
}


/** 由种子名生成主体描述（嫩× 变体：颜色更浅、体形更小、带新芽） */
function subjectOf(seedName, cropName) {
  const isNen = seedName.startsWith('嫩')
  const cropKey = cropName.startsWith('（') ? seedName.replace(/种子$/, '') : cropName
  const baseKey = cropKey.startsWith('嫩') ? cropKey.slice(1) : cropKey
  const t = T[baseKey] || `棕褐|${shapeOf(baseKey)}`
  let [c, f] = t.split('|')
  f = f || shapeOf(baseKey)
  let subj = `${seedName.replace(/种子$/, '')}的种子：${f}，主色${c}`
  if (isNen && !baseKey.startsWith('嫩')) {
    subj += '；整体色调更浅嫩、体形略小、顶端带一粒新芽（「嫩」变体，与同作物的成熟种子成对区分）'
  }
  return subj
}


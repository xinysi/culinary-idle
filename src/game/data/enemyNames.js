/**
 * 只改名字：把 `REGION_OPP_NAMES[region.id]` 按**区域内等级升序**贴到 `region.opponents` 上。
 * 返回 [{ region, oldName, newName, level, key }] 供 UI/清单使用（也便于守卫断言）。
 * ⚠️ 绝不重排 `opponents` 数组本身：掉落是按**下标**分配的（`rebalanceDrops(o, ri*10+oi)`），
 *    重排等于改掉落 = 违反数据铁律。
 */
export function applyRegionOpponentNames(regions) {
  const renamed = []
  for (const r of regions) {
    const names = REGION_OPP_NAMES[r.id]
    if (!names) continue
    const order = r.opponents.map((o, i) => ({ o, i })).sort((a, b) => a.o.level - b.o.level || a.i - b.i)
    order.forEach(({ o }, rank) => {
      // 立绘文件名（2026-09-21）：与 `敌名清单.xlsx` 的「建议图片文件名」同一排序口径（区内等级升序）
      o.imgKey = `enemy_${r.id}_${String(rank + 1).padStart(2, '0')}`
      const newName = names[rank] ?? o.name
      if (newName === o.name) return
      renamed.push({ region: r.name, oldName: o.name, newName, level: o.level })
      o.name = newName
    })
  }
  return renamed
}

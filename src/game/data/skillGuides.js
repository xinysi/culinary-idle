/** 兜底：没写专属文案的技能，按类别给一段诚实的通用说明（不编机制）。 */
export function guideFor(def, ctx = {}) {
  const g = SKILL_GUIDES[def?.id]
  if (g) return { title: def.name, intro: g.what, points: g.points }
  const n = ctx.count
  const unit = def?.category === 'production' || ctx.isProduction ? '配方' : '目标'
  return {
    title: def?.name ?? '技能',
    intro: def?.desc ? `${def.desc}。` : '这个页面用于该技能的日常操作。',
    points: [
      n != null ? `本页共 **${n} 个${unit}**，按等级段分档，点上面的段标签切换。` : `本页按等级段分档，点上面的段标签切换。`,
      def?.category === 'production' || ctx.isProduction
        ? '制作失败会消耗材料、只拿半额经验；「制作队列」可连续制作（每 3 秒 1 次）。'
        : '挂机会按目标间隔自动产出，右侧「挂机中」可暂停 / 停止。',
      '精通 0~100 级给经验倍率与产量/成功率加成，卡片上直接标着当前进度。',
    ],
  }
}

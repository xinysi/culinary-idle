export function currentGuideStageId(combatLevel) {
  const thresholds = [
    { id: 'beginner', max: 10 },
    { id: 'early', max: 30 },
    { id: 'mid', max: 60 },
    { id: 'late', max: 85 },
    { id: 'lategame', max: 99 },
  ]
  for (const t of thresholds) if (combatLevel <= t.max) return t.id
  return 'endgame'
}
